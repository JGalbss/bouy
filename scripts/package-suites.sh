#!/bin/sh
# Writes the package suites of tests/package-suites (docs/design/testing.md section 5.8 d): the
# own test suites of the most downloaded npm packages. No step names a package.
#
# 1. tests/package-suites/sources.json: the first $SUITES_TOP packages of
#    tests/ecosystem/ranking.json that have a program, each at the version of
#    tests/ecosystem/package.json, with the repository and the commit of that version. The
#    commit is the gitHead of the registry, or else the tag of the version. A package is out
#    when its source is a directory of a monorepo, when it has no test script, or when its
#    repository does not have the commit.
# 2. The checkouts: each repository at its commit in $XDG_CACHE_HOME/buoy/package-suites,
#    one pnpm workspace, whose install of the dev dependencies runs no install script.
#    tests/package-suites/pnpm-lock.yaml pins it.
# 3. tests/package-suites/lookup.json: `buoy-suites package-suites --plan` reads the test
#    script of each checkout and writes the command line of each test file.
# 4. tests/package-suites/node.txt: scripts/freeze-expectations.sh runs each test file three
#    times on Node.
#
# Then `buoy-suites package-suites --update` records Buoy's outcomes in expectations.txt and
# summary.json.
#
# Usage: scripts/package-suites.sh. It needs git, jq, curl, pnpm, and the node of
# .node-version. `scripts/package-suites.sh install` only clones the commits of sources.json
# and installs the locked dev dependencies.

set -eu

root=$(cd "$(dirname "$0")/.." && pwd)
tier="$root/tests/package-suites"
cache="${XDG_CACHE_HOME:-$HOME/.cache}/buoy/package-suites"
top=${SUITES_TOP:-250}

mkdir -p "$tier" "$cache"

# Clones the repository $2 at the commit or tag $3 into $cache/$1, unless it is there.
clone() {
    target="$cache/$1"
    if [ -d "$target/.git" ] && [ "$(git -C "$target" rev-parse HEAD 2>/dev/null)" = "$3" ]; then
        return 0
    fi
    rm -rf "$target"
    mkdir -p "$target"
    git -C "$target" init -q &&
        git -C "$target" remote add origin "$2" &&
        GIT_TERMINAL_PROMPT=0 git -C "$target" fetch -q --depth 1 origin "$3" 2>/dev/null &&
        git -C "$target" -c advice.detachedHead=false checkout -q FETCH_HEAD ||
        {
            rm -rf "$target"
            return 1
        }
}

# The workspace of the checkouts that have a source.
workspace() {
    printf '{"name": "@buoy/package-suites", "private": true}\n' >"$cache/package.json"
    {
        echo "# Generated by scripts/package-suites.sh."
        echo "packages:"
        jq -r '.packages[] | select(.commit) | "  - \"\(.name)\""' "$tier/sources.json"
    } >"$cache/pnpm-workspace.yaml"
}

if [ "${1:-}" = install ]; then
    jq -r '.packages[] | select(.commit) | "\(.name) \(.repository) \(.commit)"' "$tier/sources.json" |
        while read -r name repository commit; do
            clone "$name" "$repository" "$commit" || echo "cannot clone $name at $commit" >&2
        done
    workspace
    cp "$tier/pnpm-lock.yaml" "$cache/pnpm-lock.yaml"
    cd "$cache" && pnpm install --frozen-lockfile --ignore-scripts
    exit 0
fi

# 1. The sources, with each clone, since a tag becomes a commit only when it is fetched.
jq -r --argjson top "$top" '[.packages[] | select(.kind == "program")][:$top][] | "\(.rank) \(.name)"' \
    "$root/tests/ecosystem/ranking.json" >"$cache/.ranked"
: >"$cache/.records"
while read -r rank name; do
    version=$(jq -r --arg name "$name" '.dependencies[$name] // empty' "$root/tests/ecosystem/package.json")
    record() {
        jq -n --argjson rank "$rank" --arg name "$name" --arg version "$version" "$@" >>"$cache/.records"
    }
    if [ -z "$version" ]; then
        record --arg reason "not in tests/ecosystem/package.json" '{rank: $rank, name: $name, version: $version, excluded: $reason}'
        continue
    fi
    encoded=$(printf '%s' "$name" | sed 's#/#%2F#')
    manifest=$(curl -sf "https://registry.npmjs.org/$encoded/$version" || true)
    if [ -z "$manifest" ]; then
        record --arg reason "the registry has no manifest of the version" '{rank: $rank, name: $name, version: $version, excluded: $reason}'
        continue
    fi
    facts=$(printf '%s' "$manifest" | jq -r '
        def url: (.repository | if type == "object" then .url else . end) // ""
            | sub("^git\\+"; "") | sub("^git://"; "https://") | sub("^ssh://git@"; "https://")
            | sub("^git@(?<host>[^:]+):"; "https://\(.host)/") | sub("^github:"; "https://github.com/")
            | if test("^[^/:]+/[^/:]+$") then "https://github.com/\(.)" else . end
            | sub("#.*$"; "");
        [url, (.repository.directory? // ""), (.gitHead // ""),
         ((.scripts.test // "") | if test("no test specified") then "" else . end)] | @tsv' || true)
    repository=$(printf '%s' "$facts" | cut -f1)
    directory=$(printf '%s' "$facts" | cut -f2)
    head=$(printf '%s' "$facts" | cut -f3)
    script=$(printf '%s' "$facts" | cut -f4)
    reason=
    if [ -z "$repository" ]; then
        reason="the manifest names no repository"
    elif [ -n "$directory" ] && [ "$directory" != "." ]; then
        reason="a package of a monorepo: its suite needs the install of the whole repository"
    elif [ -z "$script" ]; then
        reason="no test script"
    elif ! printf '%s' "$script" | grep -Eqw 'mocha|_mocha|ava|tape|tap|jest|vitest|uvu|node|npm|pnpm|yarn|run-s|run-p|npm-run-all'; then
        # The plan reads the same words, so the clone of such a package would give no run.
        reason="the test script runs no test runner that the plan knows: $script"
    fi
    if [ -n "$reason" ]; then
        record --arg reason "$reason" '{rank: $rank, name: $name, version: $version, excluded: $reason}'
        continue
    fi
    commit=
    for reference in $head "v$version" "$version" "$name@$version"; do
        if clone "$name" "$repository" "$reference"; then
            commit=$(git -C "$cache/$name" rev-parse HEAD)
            break
        fi
    done
    if [ -z "$commit" ]; then
        record --arg repository "$repository" --arg reason "the repository has neither the gitHead nor the tag of the version" \
            '{rank: $rank, name: $name, version: $version, repository: $repository, excluded: $reason}'
        continue
    fi
    # The root of a monorepo installs its packages from the repository, as pnpm cannot in
    # this workspace.
    if [ -f "$cache/$name/pnpm-workspace.yaml" ] || [ -f "$cache/$name/lerna.json" ] ||
        ! jq -e '.workspaces == null and ([(.dependencies, .devDependencies, .optionalDependencies)
            | values | .[] | strings | select(test("^(workspace|link|file|portal):"))] | length == 0)' \
            "$cache/$name/package.json" >/dev/null 2>&1; then
        rm -rf "${cache:?}/$name"
        record --arg repository "$repository" --arg reason "the root of a monorepo: its suite needs the install of the whole repository" \
            '{rank: $rank, name: $name, version: $version, repository: $repository, excluded: $reason}'
        continue
    fi
    record --arg repository "$repository" --arg commit "$commit" \
        '{rank: $rank, name: $name, version: $version, repository: $repository, commit: $commit}'
done <"$cache/.ranked"
jq -s '{generated_by: "scripts/package-suites.sh", ranking: "tests/ecosystem/ranking.json", packages: .}' \
    "$cache/.records" >"$tier/sources.json"
rm -f "$cache/.ranked" "$cache/.records"

# 2. The install. A lockfile of an earlier run keeps the versions that it pinned. When pnpm
# cannot install the direct dependencies of a checkout, the package leaves the tier with the
# code of the error, and the install starts again.
[ ! -f "$tier/pnpm-lock.yaml" ] || cp "$tier/pnpm-lock.yaml" "$cache/pnpm-lock.yaml"
while :; do
    workspace
    if (cd "$cache" && pnpm install --ignore-scripts) >"$cache/.install" 2>&1; then
        break
    fi
    failed=$(sed -n "s#.*a direct dependency of $cache/##p" "$cache/.install" | head -n 1)
    code=$(grep -o 'ERR_PNPM_[A-Z0-9_]*' "$cache/.install" | head -n 1)
    if [ -z "$failed" ]; then
        cat "$cache/.install" >&2
        exit 1
    fi
    jq --arg name "$failed" --arg reason "pnpm cannot install its dev dependencies: $code" '
        .packages |= map(if .name == $name then del(.commit) + {excluded: $reason} else . end)' \
        "$tier/sources.json" >"$cache/.sources"
    mv "$cache/.sources" "$tier/sources.json"
    rm -rf "${cache:?}/$failed"
done
rm -f "$cache/.install"
cp "$cache/pnpm-lock.yaml" "$tier/pnpm-lock.yaml"

# 3 and 4. The plan and the oracle.
cd "$root"
cargo run -q --release -p buoy-suites -- package-suites --plan
scripts/freeze-expectations.sh tests/package-suites
echo "wrote tests/package-suites: $(grep -c ' pass$' "$tier/node.txt") test files pass on Node"
