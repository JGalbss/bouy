#!/bin/sh
# Writes the generated tier of the top npm packages, tests/ecosystem (docs/design/testing.md
# section 5.8 f). Nothing in the tier is written by hand, and no step names a package.
#
# 1. tests/ecosystem/ranking.json: scripts/rank-packages.sh with the top 1,000. Kept when it
#    exists; delete it to rank again.
# 2. tests/ecosystem/package.json: each package of rank 1 to 1,000 whose latest version has a
#    JavaScript entry, at the highest release of its most downloaded major. pnpm installs
#    them into tests/ecosystem/node_modules, which git ignores, and pnpm-lock.yaml pins them.
# 3. tests/ecosystem/<name>/exports.cjs and exports.mjs: the program that requires or imports
#    the package and prints the shape of what it gets, with describe.cjs and describe.mjs. A
#    package gets exports.cjs when its installed version has a CommonJS entry, exports.mjs
#    when it has an ES module entry, and both when it has both.
# 4. The Node oracle: scripts/freeze-expectations.sh on each directory, at most four at once.
# 5. tests/ecosystem/packages.json: each ranked package with its programs, or the reason
#    that it has none. A package is out when its latest version is a platform binary or
#    only types, when Node cannot load it (a CLI, a browser-only package, a package that
#    needs its install script), when two Node runs print different shapes, or when Node
#    does not exit after it loads. Its directory goes.
#
# Then `buoy-suites ecosystem --update` records Buoy's outcomes in expectations.txt and
# summary.json.
#
# Usage: scripts/ecosystem.sh. It needs jq, pnpm, perl, and the node of .node-version, and it
# takes about an hour. `scripts/ecosystem.sh install` only installs the locked packages.

set -eu

root=$(cd "$(dirname "$0")/.." && pwd)
tier="$root/tests/ecosystem"
top=1000
# The seconds that one freeze of a package may take: four node runs.
deadline=120

mkdir -p "$tier"
cd "$tier"

if [ "${1:-}" = install ]; then
    pnpm install --frozen-lockfile
    exit 0
fi

if [ ! -f ranking.json ]; then
    RANK_TOP=$top RANK_PAGES=15 RANK_OUTPUT=tests/ecosystem/ranking.json "$root/scripts/rank-packages.sh"
fi

cat >pnpm-workspace.yaml <<'EOF'
# Generated by scripts/ecosystem.sh. This file makes tests/ecosystem a workspace of its own,
# apart from the workspace of the repository, so its packages install only on request.
packages:
  - .
EOF

jq --argjson top "$top" '{
    name: "@buoy/ecosystem",
    private: true,
    description: "Generated by scripts/ecosystem.sh from ranking.json: the top npm packages, each at the highest release of its most downloaded major.",
    dependencies: (.packages
        | map(select(.rank <= $top and .kind == "program"))
        | map({key: .name, value: (.versions | max_by(.share) | .version)})
        | sort_by(.key) | from_entries)
}' ranking.json >package.json
pnpm install

# The shape printer, once for each module system.
body='// Generated by scripts/ecosystem.sh. Prints the shape of a loaded module, as Bun'"'"'s
// test/exports/generate-exports.mjs records the built-in modules: each key, sorted, with its
// type, two levels deep. A function shows its length and the members of its prototype. The
// only calls are the `is*` predicates of the first level, on fixed values.

const LIMIT = 100;
const PROBES = [undefined, null, 0, 1.5, "", "a", [], {}, true];

function attempt(load) {
  try {
    return { value: load() };
  } catch (error) {
    return { error };
  }
}

function errorName(error) {
  const parts = attempt(() => [error.name, error.code].filter((part) => typeof part === "string"));
  return (parts.value ?? []).join(" ") || "a non-error";
}

function members(prototype) {
  if (prototype === null || typeof prototype !== "object") return [];
  const names = attempt(() => Object.getOwnPropertyNames(prototype));
  return (names.value ?? []).filter((name) => name !== "constructor").sort();
}

function shape(value) {
  if (value === null) return "null";
  if (typeof value === "function") {
    const own = members(attempt(() => value.prototype).value);
    if (own.length === 0) return `function/${value.length}`;
    return `class/${value.length} {${own.join(", ")}}`;
  }
  if (typeof value !== "object") return typeof value;
  const tag = attempt(() => Object.prototype.toString.call(value).slice(8, -1)).value;
  return tag === "Object" ? "object" : `object ${tag}`;
}

function outcome(result) {
  if (typeof result === "boolean") return String(result);
  if (result !== null && typeof result === "object" && typeof result.then === "function") {
    attempt(() => result.then(undefined, () => {}));
    return "promise";
  }
  return typeof result;
}

function predicate(name, value) {
  const applies = typeof value === "function" && /^is[A-Z]/.test(name) && value.length <= 2;
  if (!applies) return "";
  const results = PROBES.map((probe) => {
    const result = attempt(() => value(probe));
    return "error" in result ? "throws" : outcome(result.value);
  });
  return ` (${results.join(", ")})`;
}

function write(lines, depth, key, read) {
  const indent = "  ".repeat(depth);
  if ("error" in read) {
    lines.push(`${indent}${key}: throws ${errorName(read.error)}`);
    return;
  }
  const value = read.value;
  const name = depth === 0 ? attempt(() => value.name).value : key;
  const called = depth < 2 ? predicate(String(name), value) : "";
  lines.push(`${indent}${key}: ${shape(value)}${called}`);
  const nested = value !== null && (typeof value === "object" || typeof value === "function");
  if (depth === 2 || !nested || Array.isArray(value)) return;
  const keys = attempt(() => Object.keys(value).sort()).value ?? [];
  for (const child of keys.slice(0, LIMIT)) {
    write(lines, depth + 1, child, attempt(() => value[child]));
  }
  if (keys.length > LIMIT) lines.push(`${indent}  ... ${keys.length - LIMIT} more keys`);
}

function describe(label, read) {
  if ("error" in read) {
    const message = attempt(() => String(read.error.message).split("\n")[0]).value ?? "";
    console.log(`load failed: ${errorName(read.error)}: ${message}`);
    return;
  }
  const lines = [];
  write(lines, 0, label, read);
  console.log(lines.join("\n"));
}
'
printf '%s\nmodule.exports = { attempt, describe };\n' "$body" >describe.cjs
printf '%s\nexport { attempt, describe };\n' "$body" >describe.mjs

# The directory of each package, then each program that it gets.
jq -r '.dependencies | keys[]' package.json >"$tier/.names"
while read -r name; do
    manifest="node_modules/$name/package.json"
    format=$(jq -L "$root/scripts" -r 'include "package-entry"; entry | format' "$manifest")
    up=$(printf '%s' "$name" | sed 's#[^/]*#..#g')
    mkdir -p "$name"
    rm -f "$name"/exports.*
    case $format in
    cjs | dual)
        cat >"$name/exports.cjs" <<EOF
// Generated by scripts/ecosystem.sh. Requires the package and prints the shape of what it gets.
const { attempt, describe } = require("$up/describe.cjs");

describe("module.exports", attempt(() => require("$name")));
EOF
        ;;
    esac
    case $format in
    esm | dual)
        cat >"$name/exports.mjs" <<EOF
// Generated by scripts/ecosystem.sh. Imports the package and prints the shape of its namespace.
import { describe } from "$up/describe.mjs";

describe("namespace", await import("$name").then((value) => ({ value }), (error) => ({ error })));
EOF
        ;;
    esac
done <"$tier/.names"

# The oracle, four packages at once. A freeze past the deadline loses its process group.
cd "$root"
export deadline
sed 's#^#tests/ecosystem/#' "$tier/.names" | xargs -P 4 -n 1 sh -c '
    perl -e '"'"'
        my $seconds = shift;
        my $pid = fork;
        if (!$pid) { setpgrp(0, 0); exec @ARGV; exit 127 }
        $SIG{ALRM} = sub { kill "KILL", -$pid; exit 142 };
        alarm $seconds;
        waitpid($pid, 0);
        exit($? >> 8);
    '"'"' "$deadline" scripts/freeze-expectations.sh "$0" >/dev/null 2>"$0/.freeze" ||
        echo "$?" >"$0/.failed"
'
cd "$tier"

# The record of each package. A program that Node cannot run goes, with its reason, and so
# does the directory of a package that keeps no program.
for name in $(cat "$tier/.names"); do
    reason=
    programs=
    dropped=
    if [ -f "$name/.failed" ]; then
        if grep -q "two node runs" "$name/.freeze"; then
            reason="two Node runs print different shapes"
        else
            reason="Node does not exit after it loads the package"
        fi
    else
        for program in "$name"/exports.cjs "$name"/exports.mjs; do
            [ -f "$program" ] || continue
            first=$(head -n 1 "$program.stdout")
            case $first in
            "load failed: "*) reason="Node cannot load it: ${first#load failed: }" ;;
            *)
                if [ -f "$program.status" ]; then
                    reason="Node exits with status $(cat "$program.status") after it loads the package"
                else
                    programs="$programs ${program##*/}"
                    continue
                fi
                ;;
            esac
            dropped="$dropped ${program##*/}"
            rm -f "$program" "$program.stdout" "$program.status"
        done
    fi
    rm -f "$name/.freeze" "$name/.failed"
    version=$(jq -r --arg name "$name" '.dependencies[$name]' package.json)
    [ -n "$programs" ] || rm -rf "$name"
    # An absolute path of this machine never enters the record.
    jq -n --arg name "$name" --arg version "$version" --arg programs "$programs" \
        --arg dropped "$dropped" --arg reason "$reason" '
        def words: split(" ") | map(select(. != ""));
        ($reason | gsub("(?<lead>^|[ '"'"'\"(])(file://)?/[^ '"'"'\")]+"; "\(.lead)<path>") | .[0:200]) as $reason
        | {name: $name, version: $version}
        + if $programs == "" then {excluded: $reason}
          else {programs: ($programs | words)}
            + if $dropped == "" then {} else {dropped: {programs: ($dropped | words), reason: $reason}} end
          end'
done >"$tier/.records"
rm -f "$tier/.names"

jq -s --slurpfile ranking ranking.json --argjson top "$top" '
    (map({key: .name, value: .}) | from_entries) as $records
    | {
        generated_by: "scripts/ecosystem.sh",
        ranking: "ranking.json",
        packages: [$ranking[0].packages[] | select(.rank <= $top) | . as $ranked
            | ($records[.name] // {name, version: .latest,
                excluded: (if .kind == "platform-binary" then "a platform binary: its package.json names os or cpu"
                           else "only types: its entry points name only type declarations" end)})
            | {rank: $ranked.rank} + .]
      }' "$tier/.records" >packages.json
rm -f "$tier/.records"
echo "wrote tests/ecosystem: $(jq '[.packages[] | select(.programs)] | length' packages.json) packages with programs, $(jq '[.packages[] | select(.excluded)] | length' packages.json) excluded"
