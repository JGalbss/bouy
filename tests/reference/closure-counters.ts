let calls = 0;
function counted<T extends unknown[], R>(f: (...args: T) => R) {
  return (...args: T): R => {
    calls++;
    return f(...args);
  };
}
const double = counted((x: number) => x * 2);
console.log(double(2), double(5), calls);

