//! The runner of `buoy-suites packages` on a small fake tree, with a fake `buoy` that prints
//! each program's own text, so `pnpm check` covers the runner with no VM and no fake server.

use std::fs;
use std::os::unix::fs::PermissionsExt;
use std::path::{Path, PathBuf};
use std::time::Duration;

use buoy_suites::outcome::Outcome;
use buoy_suites::packages::{self, Options};

/// A `buoy run` that rejects a program whose path holds `rejected`, and otherwise prints the
/// program's text and exits with 0.
const FAKE_BUOY: &str = r#"#!/bin/sh
case "$2" in
*rejected*)
    printf '{"status":2,"diagnostics":["BUOY201"]}' > "$BUOY_RESULT_FILE"
    exit 2
    ;;
esac
cat "$2"
printf '{"status":0}' > "$BUOY_RESULT_FILE"
"#;

struct FakeTree {
    root: PathBuf,
}

impl FakeTree {
    fn new(name: &str, extra: &[(&str, &str)]) -> Self {
        let root = Path::new(env!("CARGO_TARGET_TMPDIR")).join(format!("fake-packages-{name}"));
        let _ = fs::remove_dir_all(&root);
        let files = [
            (".node-version", "25.9.0\n"),
            ("buoy", FAKE_BUOY),
            ("tests/equivalence/ai/text.ts", ""),
            ("tests/npm/good/main.mjs", "good\n"),
            ("tests/npm/good/main.mjs.stdout", "good\n"),
            ("tests/npm/good/node_modules/x/main.mjs", "not a program\n"),
            ("tests/npm/rejected/main.cjs", "x\n"),
            ("tests/npm/rejected/main.cjs.stdout", "x\n"),
            ("tests/packages/p@1/exports.mjs", "printed\n"),
            (
                "tests/packages/p@1/exports.mjs.stdout",
                "node printed this\n",
            ),
            ("tests/packages/p@1/main.mjs", "main\n"),
            ("tests/packages/p@1/main.mjs.stdout", "main\n"),
            ("tests/packages/p@1/lib/helper.mjs", "not a program\n"),
            ("tests/packages/@s/rejected@2/exports.cjs", "y\n"),
            ("tests/packages/@s/rejected@2/exports.cjs.stdout", ""),
            ("tests/packages/@s/rejected@2/exports.cjs.status", "1\n"),
        ];
        for (path, text) in files.iter().chain(extra) {
            let path = root.join(path);
            fs::create_dir_all(path.parent().expect("a parent")).expect("writable");
            fs::write(path, text).expect("writable");
        }
        fs::set_permissions(root.join("buoy"), fs::Permissions::from_mode(0o755))
            .expect("the fake buoy is executable");
        Self { root }
    }

    fn options(&self, update: bool) -> Options {
        Options {
            root: self.root.clone(),
            output: self.root.join("output"),
            buoy: self.root.join("buoy"),
            filter: None,
            update,
            jobs: 2,
            deadline: Duration::from_secs(20),
        }
    }

    fn read(&self, path: &str) -> String {
        fs::read_to_string(self.root.join(path)).unwrap_or_default()
    }
}

#[test]
fn an_update_records_each_outcome_and_the_next_run_matches() {
    let tree = FakeTree::new("update", &[]);
    let report = packages::run(&tree.options(true)).expect("the update runs");
    assert_eq!(
        tree.read("tests/npm/expectations.txt"),
        "# Generated by `buoy-suites packages --update`. Do not edit. 2 programs of tests/npm.\n\
         good/main.mjs pass\n\
         rejected/main.cjs rejected\n"
    );
    assert_eq!(
        tree.read("tests/packages/expectations.txt"),
        "# Generated by `buoy-suites packages --update`. Do not edit. 3 programs of tests/packages.\n\
         @s/rejected@2/exports.cjs rejected\n\
         p@1/exports.mjs fail\n\
         p@1/main.mjs pass\n"
    );
    let summary = report
        .summary
        .expect("a run of every program has a summary");
    assert_eq!(summary.total, 3);
    assert_eq!(summary.outcomes.get(Outcome::Fail), 1);
    assert_eq!(summary.groups["kind"]["exports.mjs"].get(Outcome::Fail), 1);
    assert_eq!(
        summary.groups["program"]["p@1/main.mjs"].get(Outcome::Pass),
        1
    );
    assert_eq!(summary.blockers.len(), 1);
    assert_eq!(
        (
            summary.blockers[0].blocker.as_str(),
            summary.blockers[0].only
        ),
        ("BUOY201", 1)
    );
    assert!(
        tree.read("tests/packages/summary.json")
            .contains("\"suite\": \"packages\"")
    );

    let again = packages::run(&tree.options(false)).expect("the second run");
    assert!(!again.fails(), "{}", again.text());
}

#[test]
fn a_changed_outcome_fails_and_names_the_update_command() {
    let tree = FakeTree::new(
        "stale",
        &[(
            "tests/npm/expectations.txt",
            "good/main.mjs rejected\nrejected/main.cjs pass\n",
        )],
    );
    let report = packages::run(&tree.options(false)).expect("the run");
    assert!(report.fails());
    let text = report.text();
    assert!(
        text.contains("1 regressions:\n  rejected/main.cjs rejected (previously pass)"),
        "{text}"
    );
    assert!(
        text.contains("good/main.mjs: the file says rejected"),
        "{text}"
    );
    assert!(text.contains(packages::UPDATE), "{text}");
}

#[test]
fn a_program_without_output_and_an_output_without_program_stop_the_run() {
    let missing = FakeTree::new("missing", &[("tests/npm/new/main.mjs", "new\n")]);
    let error = packages::run(&missing.options(false)).expect_err("no recorded stdout");
    assert!(
        error.contains("scripts/freeze-expectations.sh tests/npm"),
        "{error}"
    );
    let orphan = FakeTree::new("orphan", &[("tests/packages/p@1/main.cjs.stdout", "x\n")]);
    let error = packages::run(&orphan.options(false)).expect_err("an orphan output");
    assert!(error.contains("main.cjs.stdout"), "{error}");
    let mut filtered = orphan.options(true);
    filtered.filter = Some("p@1".to_owned());
    assert!(
        packages::run(&filtered).is_err(),
        "an update runs every program"
    );
}
