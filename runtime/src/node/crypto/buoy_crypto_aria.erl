-type schedule() :: [binary()].
-export_type([schedule/0]).

%% The round keys of Key (16, 24, or 32 bytes): ek1 ... ek(n+1) for
%% encryption, or dk1 ... dk(n+1) for decryption (section 2.2).
-spec schedule(binary(), boolean()) -> schedule().
schedule(Key, Encrypt) ->
    Bits = byte_size(Key) * 8,
    KL = binary:part(Key, 0, 16),
    KR = <<(binary:part(Key, 16, byte_size(Key) - 16))/binary, 0:(256 - Bits)>>,
    {CK1, CK2, CK3} = case Bits of
        128 -> {c1(), c2(), c3()};
        192 -> {c2(), c3(), c1()};
        256 -> {c3(), c1(), c2()}
    end,
    W0 = KL,
    W1 = crypto:exor(fo(W0, CK1), KR),
    W2 = crypto:exor(fe(W1, CK2), W0),
    W3 = crypto:exor(fo(W2, CK3), W1),
    [A, B, C, D] = [binary:decode_unsigned(W) || W <- [W0, W1, W2, W3]],
    All = [A bxor rotr(B, 19), B bxor rotr(C, 19), C bxor rotr(D, 19), rotr(A, 19) bxor D,
           A bxor rotr(B, 31), B bxor rotr(C, 31), C bxor rotr(D, 31), rotr(A, 31) bxor D,
           A bxor rotl(B, 61), B bxor rotl(C, 61), C bxor rotl(D, 61), rotl(A, 61) bxor D,
           A bxor rotl(B, 31), B bxor rotl(C, 31), C bxor rotl(D, 31), rotl(A, 31) bxor D,
           A bxor rotl(B, 19)],
    Ek = [<<K:128>> || K <- lists:sublist(All, Bits div 32 + 9)],
    case Encrypt of
        true -> Ek;
        false ->
            [Last | Middle] = lists:reverse(Ek),
            [First | Inner] = lists:reverse(Middle),
            [Last | [a(K) || K <- lists:reverse(Inner)]] ++ [First]
    end.

c1() -> <<16#517cc1b727220a94fe13abe8fa9a6ee0:128>>.
c2() -> <<16#6db14acc9e21c820ff28b1d5ef5de2b0:128>>.
c3() -> <<16#db92371d2126e9700324977504e8c90e:128>>.

rotr(X, N) -> ((X bsr N) bor (X bsl (128 - N))) band ?M128.
rotl(X, N) -> rotr(X, 128 - N).

%% One 16-byte block under a schedule (section 2.3): odd and even rounds,
%% then the last round with two keys.
-spec block(schedule(), binary()) -> binary().
block(Keys, Block) -> rounds(Keys, Block, odd).

rounds([K, Last], P, _) -> crypto:exor(sl2(crypto:exor(P, K)), Last);
rounds([K | Rest], P, odd) -> rounds(Rest, fo(P, K), even);
rounds([K | Rest], P, even) -> rounds(Rest, fe(P, K), odd).

fo(D, K) -> a(sl1(crypto:exor(D, K))).
fe(D, K) -> a(sl2(crypto:exor(D, K))).

-compile({inline, [s/2]}).
s(T, X) -> element(X + 1, T).

