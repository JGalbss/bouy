%% The bindings of Node that Bouy does not implement yet, with the shape that
%% Node 25.9.0 gives them (recorded with the oracle): a function member throws
%% ERR_BOUY_NOT_IMPLEMENTED when called, a class member when constructed, and
%% a value member holds Node's value. So Node's lib loads the modules that
%% read such a binding at load time, and a program fails only when it calls
%% the missing native code. A function whose name starts with set does
%% nothing, as the setters of host callbacks that the bootstrap calls. To
%% implement a binding, write
%% bouy_binding_<name>.erl; it takes precedence over the entry here.
-module(bouy_node_stubs).

-export([has/1, binding/1]).

-spec has(binary()) -> boolean().
has(Name) -> is_map_key(Name, specs()).

-spec binding(binary()) -> term().
binding(Name) ->
    #{Name := Members} = specs(),
    bouy_node:object([member(Name, M) || M <- bouy_heap:array_items(Members)]).

member(Binding, Member) ->
    [Key, Kind | Rest] = bouy_heap:array_items(Member),
    {Key, value(Binding, Key, Kind, Rest)}.

value(_Binding, <<"set", _/binary>> = Key, <<"function">>, [Length]) ->
    bouy_node:fn(Key, Length, fun(_, _) -> undefined end);
value(Binding, Key, <<"function">>, [_Length]) ->
    bouy_node:not_implemented(Binding, bouy_ref_string:to_utf8(Key));
value(Binding, Key, <<"class">>, [Length]) ->
    bouy_node:missing_constructor(Binding, bouy_ref_string:to_utf8(Key), Length);
value(_Binding, _Key, <<"typed">>, [Kind, Length]) ->
    bouy_node:typed_array(Kind, Length);
value(_Binding, _Key, <<"value">>, [Value]) ->
    Value.


%% The members of each binding, parsed once per realm.
specs() ->
    case erlang:get({?MODULE, specs}) of
        undefined ->
            Object = bouy_node:from_json(json()),
            Specs = maps:from_list([{K, bouy_heap:get(Object, K)} || K <- bouy_heap:enumerable_keys(Object)]),
            erlang:put({?MODULE, specs}, Specs),
            Specs;
        Specs ->
            Specs
    end.

