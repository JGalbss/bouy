rounding_test_() ->
    Cases = [
        {round, 2.5, 3}, {round, -2.5, -2}, {round, 0.49999999999999994, 0}, {round, -0.4, -0.0},
        {round, 1.5, 2}, {round, -1.5, -1}, {round, 9007199254740992, 9007199254740992},
        {floor, -4.5, -5}, {floor, 4.7, 4}, {floor, -0.0, -0.0}, {ceil, 4.1, 5}, {ceil, -0.3, -0.0},
        {trunc, -4.7, -4}, {trunc, -0.3, -0.0}, {trunc, 1.0e300, 1.0e300}, {floor, 'Infinity', 'Infinity'},
        {abs, -5, 5}, {abs, -0.0, 0.0}, {abs, '-Infinity', 'Infinity'}, {sign, -3, -1}, {sign, -0.0, -0.0},
        {sign, 'NaN', 'NaN'}, {sign, 0.5, 1}
    ],
    [?_assert(same(bouy_math:F([X]), Expected)) || {F, X, Expected} <- Cases] ++
        [?_assert(is_integer(bouy_math:floor([4.7]))), ?_assert(is_integer(bouy_math:round([2.5])))].

min_max_test_() ->
    [
        ?_assertEqual('-Infinity', bouy_math:max([])),
        ?_assertEqual('Infinity', bouy_math:min([])),
        ?_assertEqual(3, bouy_math:max([1, <<"3">>, 2])),
        ?_assertEqual('NaN', bouy_math:min([<<"x">>, 1])),
        ?_assertEqual('NaN', bouy_math:max([1, 'NaN'])),
        ?_assert(same(bouy_math:max([-0.0, 0]), 0)),
        ?_assert(same(bouy_math:min([0, -0.0]), -0.0)),
        ?_assertEqual(-5, bouy_math:max(['-Infinity', -5]))
    ].

other_test_() ->
    [
        ?_assertEqual(5.0, bouy_math:hypot([3, 4])),
        ?_assertEqual(0, bouy_math:hypot([])),
        ?_assertEqual('Infinity', bouy_math:hypot(['NaN', 'Infinity'])),
        ?_assertEqual(3.0, bouy_math:hypot([-3])),
        ?_assertEqual(5.5, bouy_math:fround([5.5])),
        ?_assertEqual(5.050000190734863, bouy_math:fround([5.05])),
        ?_assertEqual('Infinity', bouy_math:fround([1.0e300])),
        ?_assertEqual(31, bouy_math:clz32([1])),
        ?_assertEqual(32, bouy_math:clz32([0])),
        ?_assertEqual(12, bouy_math:imul([3, 4])),
        ?_assertEqual(-5, bouy_math:imul([16#ffffffff, 5])),
        ?_assert(is_float(bouy_math:random([]))),
        ?_assert(bouy_math:random([]) < 1),
        ?_assertEqual(3.141592653589793, bouy_math:'$member'(<<"PI">>)),
        ?_assertEqual(0.7071067811865476, bouy_math:'$member'(<<"SQRT1_2">>)),
        ?_assertEqual(2.0, bouy_rt:call(bouy_math:'$member'(<<"sqrt">>), [4])),
        ?_assertEqual(undefined, bouy_math:'$member'(<<"nope">>)),
        ?_assertEqual('NaN', bouy_math:sin([<<"x">>])),
        ?_assertEqual('Infinity', bouy_math:exp([1 bsl 1100]))
    ].
