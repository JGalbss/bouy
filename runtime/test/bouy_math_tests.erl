%% Bit for bit, so -0.0 and 0.0 differ.
same(A, B) when is_float(A), is_float(B) -> <<A/float>> =:= <<B/float>>;
same(A, B) -> A == B andalso not (is_float(B) andalso <<B/float>> =:= <<-0.0/float>>).

